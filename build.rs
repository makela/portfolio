//! Hashes every file under `static/` at compile time and generates a table of
//! `(url path, content hash)` pairs. Templates use it to emit cache-busting
//! URLs like `/static/style.css?v=1a2b3c4d5e6f7a8b`, so a changed file always
//! gets a new URL and browsers can cache assets forever.

use std::{
    env, fs,
    io::{self, Write},
    path::{Path, PathBuf},
};

const STATIC_DIR: &str = "static";

fn main() -> io::Result<()> {
    // Cargo rescans the whole directory, so any added, removed or edited
    // asset triggers a rebuild.
    println!("cargo::rerun-if-changed={STATIC_DIR}");

    let mut files = Vec::new();
    collect_files(Path::new(STATIC_DIR), &mut files)?;
    files.sort();

    let out_path = PathBuf::from(
        env::var_os("OUT_DIR")
            .ok_or_else(|| io::Error::new(io::ErrorKind::NotFound, "OUT_DIR is not set"))?,
    )
    .join("assets.rs");
    let mut out = fs::File::create(out_path)?;

    writeln!(out, "/// Generated by build.rs: (URL path, content hash).")?;
    writeln!(out, "pub(crate) const ASSETS: &[(&str, &str)] = &[")?;
    for file in &files {
        let relative = file
            .strip_prefix(STATIC_DIR)
            .map_err(|e| io::Error::new(io::ErrorKind::InvalidInput, e))?;
        let url = format!("/{STATIC_DIR}/{}", relative.to_string_lossy());
        let hash = fnv1a64(&fs::read(file)?);
        writeln!(out, "    ({url:?}, \"{hash:016x}\"),")?;
    }
    writeln!(out, "];")?;
    Ok(())
}

fn collect_files(dir: &Path, files: &mut Vec<PathBuf>) -> io::Result<()> {
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        if path.is_dir() {
            collect_files(&path, files)?;
        } else {
            files.push(path);
        }
    }
    Ok(())
}

/// FNV-1a: tiny, dependency-free and stable across Rust versions, which is
/// all a cache-busting key needs (it is not used for security).
fn fnv1a64(bytes: &[u8]) -> u64 {
    bytes.iter().fold(0xcbf2_9ce4_8422_2325, |hash, &b| {
        (hash ^ u64::from(b)).wrapping_mul(0x0100_0000_01b3)
    })
}
